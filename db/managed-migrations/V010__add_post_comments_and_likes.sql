CREATE TABLE post_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE RESTRICT,
 author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 root_id BIGINT,
 body VARCHAR(3000) NOT NULL,
 status VARCHAR(16) NOT NULL,
 resource_hidden BOOLEAN NOT NULL DEFAULT false,
 platform_hidden BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 removed_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uq_post_comments_id_post UNIQUE(id,post_id),
 CONSTRAINT fk_post_comments_root_post FOREIGN KEY(root_id,post_id) REFERENCES post_comments(id,post_id) ON DELETE RESTRICT,
 CONSTRAINT ck_post_comments_root CHECK(root_id IS NULL OR root_id<>id),
 CONSTRAINT ck_post_comments_status CHECK(status IN ('ACTIVE','REMOVED')),
 CONSTRAINT ck_post_comments_body CHECK(length(btrim(body,E' \t\n\r'))>0),
 CONSTRAINT ck_post_comments_version CHECK(version>=0),
 CONSTRAINT ck_post_comments_lifecycle CHECK((status='ACTIVE' AND removed_at IS NULL) OR (status='REMOVED' AND removed_at IS NOT NULL)),
 CONSTRAINT ck_post_comments_times CHECK(updated_at>=created_at AND (removed_at IS NULL OR (removed_at>=created_at AND updated_at>=removed_at)))
);
CREATE INDEX ix_post_comments_roots ON post_comments(post_id,created_at,id) WHERE root_id IS NULL;
CREATE INDEX ix_post_comments_replies ON post_comments(root_id,created_at,id) WHERE root_id IS NOT NULL;
CREATE INDEX ix_post_comments_author_id ON post_comments(author_id,id DESC);
CREATE INDEX ix_post_comments_post ON post_comments(post_id);
CREATE TABLE post_likes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE RESTRICT,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uq_post_likes_user UNIQUE(post_id,user_id),
 CONSTRAINT ck_post_likes_version CHECK(version>=0),
 CONSTRAINT ck_post_likes_times CHECK(updated_at>=created_at)
);
CREATE INDEX ix_post_likes_active ON post_likes(post_id) WHERE active=true;
CREATE INDEX ix_post_likes_user ON post_likes(user_id);
CREATE TABLE post_comment_likes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL REFERENCES post_comments(id) ON DELETE RESTRICT,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uq_post_comment_likes_user UNIQUE(comment_id,user_id),
 CONSTRAINT ck_post_comment_likes_version CHECK(version>=0),
 CONSTRAINT ck_post_comment_likes_times CHECK(updated_at>=created_at)
);
CREATE INDEX ix_post_comment_likes_active ON post_comment_likes(comment_id) WHERE active=true;
CREATE INDEX ix_post_comment_likes_user ON post_comment_likes(user_id);
CREATE TABLE comment_moderation_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL REFERENCES post_comments(id) ON DELETE RESTRICT,
 actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 scope VARCHAR(16) NOT NULL,
 action VARCHAR(16) NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 resulting_version BIGINT NOT NULL,
 CONSTRAINT uq_comment_moderation_version UNIQUE(comment_id,resulting_version),
 CONSTRAINT ck_comment_moderation_scope CHECK(scope IN ('RESOURCE','PLATFORM')),
 CONSTRAINT ck_comment_moderation_action CHECK(action IN ('HIDE','RESTORE')),
 CONSTRAINT ck_comment_moderation_reason CHECK(length(btrim(reason,E' \t\n\r'))>0),
 CONSTRAINT ck_comment_moderation_version CHECK(resulting_version>=0)
);
CREATE INDEX ix_comment_moderation_history ON comment_moderation_actions(comment_id,id DESC);
CREATE INDEX ix_comment_moderation_actor ON comment_moderation_actions(actor_id);
