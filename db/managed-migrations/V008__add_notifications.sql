DO $$ BEGIN
    IF current_database() NOT IN ('campus_plus','campus_plus_test')
       OR host(inet_server_addr()) IS DISTINCT FROM '127.0.0.1'
       OR inet_server_port() IS DISTINCT FROM 5434
       OR current_setting('server_version_num')::int NOT BETWEEN 170000 AND 179999 THEN
        RAISE EXCEPTION 'Unauthorized Campus+ PostgreSQL 17 migration target';
    END IF;
    IF NOT EXISTS(SELECT FROM public.flyway_schema_history WHERE version IN ('7','007') AND type='SQL' AND success) THEN
        RAISE EXCEPTION 'Successful reviewed V007 migration required';
    END IF;
END $$;
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    type VARCHAR(64) NOT NULL,
    source_key VARCHAR(200) NOT NULL,
    club_id BIGINT REFERENCES clubs(id) ON DELETE RESTRICT,
    announcement_id BIGINT REFERENCES club_announcements(id) ON DELETE RESTRICT,
    event_id BIGINT REFERENCES events(id) ON DELETE RESTRICT,
    participation_id BIGINT REFERENCES event_participations(id) ON DELETE RESTRICT,
    membership_id BIGINT REFERENCES club_memberships(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL,
    read_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_notifications_recipient_source UNIQUE(recipient_id,source_key),
    CONSTRAINT ck_notifications_type CHECK(type IN ('ANNOUNCEMENT_PUBLISHED','CLUB_APPROVED','CLUB_REJECTED','CLUB_SUSPENDED','CLUB_RESTORED','CLUB_ARCHIVED','MEMBERSHIP_REQUESTED','MEMBERSHIP_APPROVED','MEMBERSHIP_REJECTED','MEMBERSHIP_REMOVED','MEMBERSHIP_REAPPLICATION_ALLOWED','MEMBERSHIP_SUSPENDED','MEMBERSHIP_RESTORED','MEMBERSHIP_ROLE_CHANGED','MEMBERSHIP_OWNERSHIP_TRANSFERRED','EVENT_PUBLISHED','EVENT_RESCHEDULED','EVENT_CANCELLED','PARTICIPATION_REGISTERED','PARTICIPATION_CHECKED_IN','PARTICIPATION_REMOVED','PARTICIPATION_REAPPLICATION_ALLOWED','PARTICIPATION_CANCELLED')),
    CONSTRAINT ck_notifications_source_key CHECK(length(btrim(source_key))>0),
    CONSTRAINT ck_notifications_version CHECK(version>=0),
    CONSTRAINT ck_notifications_read_at CHECK(read_at IS NULL OR read_at>=created_at),
    CONSTRAINT ck_notifications_source CHECK(
        (type IN ('CLUB_APPROVED','CLUB_REJECTED','CLUB_SUSPENDED','CLUB_RESTORED','CLUB_ARCHIVED') AND club_id IS NOT NULL AND announcement_id IS NULL AND event_id IS NULL AND participation_id IS NULL AND membership_id IS NULL)
        OR
        (type IN ('MEMBERSHIP_REQUESTED','MEMBERSHIP_APPROVED','MEMBERSHIP_REJECTED','MEMBERSHIP_REMOVED','MEMBERSHIP_REAPPLICATION_ALLOWED','MEMBERSHIP_SUSPENDED','MEMBERSHIP_RESTORED','MEMBERSHIP_ROLE_CHANGED','MEMBERSHIP_OWNERSHIP_TRANSFERRED') AND club_id IS NOT NULL AND announcement_id IS NULL AND event_id IS NULL AND participation_id IS NULL AND membership_id IS NOT NULL)
        OR
        (type IN ('ANNOUNCEMENT_PUBLISHED') AND club_id IS NOT NULL AND announcement_id IS NOT NULL AND event_id IS NULL AND participation_id IS NULL AND membership_id IS NULL)
        OR
        (type IN ('EVENT_PUBLISHED','EVENT_RESCHEDULED','EVENT_CANCELLED') AND club_id IS NOT NULL AND announcement_id IS NULL AND event_id IS NOT NULL AND participation_id IS NULL AND membership_id IS NULL)
        OR
        (type IN ('PARTICIPATION_REGISTERED','PARTICIPATION_CHECKED_IN','PARTICIPATION_REMOVED','PARTICIPATION_REAPPLICATION_ALLOWED','PARTICIPATION_CANCELLED') AND club_id IS NOT NULL AND announcement_id IS NULL AND event_id IS NOT NULL AND participation_id IS NOT NULL AND membership_id IS NULL)
    )
);
CREATE INDEX ix_notifications_recipient_created_id ON notifications(recipient_id,created_at DESC,id DESC);
CREATE INDEX ix_notifications_unread ON notifications(recipient_id,created_at DESC,id DESC) WHERE read_at IS NULL;
CREATE INDEX ix_notifications_actor ON notifications(actor_id) WHERE actor_id IS NOT NULL;
CREATE INDEX ix_notifications_club ON notifications(club_id) WHERE club_id IS NOT NULL;
CREATE INDEX ix_notifications_announcement ON notifications(announcement_id) WHERE announcement_id IS NOT NULL;
CREATE INDEX ix_notifications_event ON notifications(event_id) WHERE event_id IS NOT NULL;
CREATE INDEX ix_notifications_participation ON notifications(participation_id) WHERE participation_id IS NOT NULL;
CREATE INDEX ix_notifications_membership ON notifications(membership_id) WHERE membership_id IS NOT NULL;
