CREATE TABLE club_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_id BIGINT REFERENCES events(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    body VARCHAR(10000) NOT NULL,
    audience VARCHAR(24) NOT NULL DEFAULT 'UNIVERSITY_STUDENTS',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMPTZ,
    withdrawn_at TIMESTAMPTZ,
    withdrawn_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    withdrawal_reason VARCHAR(1000),
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_club_announcements_title CHECK(length(btrim(title))>0),
    CONSTRAINT ck_club_announcements_body CHECK(length(btrim(body))>0),
    CONSTRAINT ck_club_announcements_audience CHECK(audience IN ('UNIVERSITY_STUDENTS','CLUB_MEMBERS')),
    CONSTRAINT ck_club_announcements_status CHECK(status IN ('DRAFT','PUBLISHED','WITHDRAWN')),
    CONSTRAINT ck_club_announcements_version CHECK(version>=0),
    CONSTRAINT ck_club_announcements_publication CHECK(
        (status='DRAFT' AND published_at IS NULL) OR (status IN ('PUBLISHED','WITHDRAWN') AND published_at IS NOT NULL)),
    CONSTRAINT ck_club_announcements_withdrawal CHECK(
        (status='WITHDRAWN' AND withdrawn_at IS NOT NULL AND withdrawn_by IS NOT NULL
            AND withdrawal_reason IS NOT NULL AND length(btrim(withdrawal_reason))>0)
        OR (status<>'WITHDRAWN' AND withdrawn_at IS NULL AND withdrawn_by IS NULL AND withdrawal_reason IS NULL)),
    CONSTRAINT ck_club_announcements_archive CHECK(archived_at IS NULL OR status IN ('DRAFT','WITHDRAWN'))
);
CREATE INDEX ix_club_announcements_club_status_published_id ON club_announcements(club_id,status,published_at DESC,id DESC);
CREATE INDEX ix_club_announcements_discovery ON club_announcements(status,published_at DESC,id DESC) WHERE archived_at IS NULL;
CREATE INDEX ix_club_announcements_event ON club_announcements(event_id) WHERE event_id IS NOT NULL;
CREATE INDEX ix_club_announcements_creator ON club_announcements(created_by);
CREATE INDEX ix_club_announcements_withdrawer ON club_announcements(withdrawn_by) WHERE withdrawn_by IS NOT NULL;

