CREATE TABLE direct_conversations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lower_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 higher_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL,
 last_message_at TIMESTAMPTZ NOT NULL,
 last_message_number BIGINT NOT NULL DEFAULT 0,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_direct_conversation_pair CHECK(0<lower_user_id AND lower_user_id<higher_user_id),
 CONSTRAINT uq_direct_conversation_pair UNIQUE(lower_user_id,higher_user_id),
 CONSTRAINT uq_direct_conversation_identity UNIQUE(id,lower_user_id,higher_user_id),
 CONSTRAINT ck_direct_conversation_counter CHECK(last_message_number>=0),
 CONSTRAINT ck_direct_conversation_version CHECK(version>=0),
 CONSTRAINT ck_direct_conversation_time CHECK(last_message_at>=created_at)
);
CREATE INDEX ix_direct_conversation_lower_inbox ON direct_conversations(lower_user_id,last_message_at DESC,id DESC);
CREATE INDEX ix_direct_conversation_higher_inbox ON direct_conversations(higher_user_id,last_message_at DESC,id DESC);

CREATE TABLE direct_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL,
 lower_user_id BIGINT NOT NULL,
 higher_user_id BIGINT NOT NULL,
 sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 message_number BIGINT NOT NULL,
 client_message_id UUID NOT NULL,
 body VARCHAR(4000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT fk_direct_message_pair FOREIGN KEY(conversation_id,lower_user_id,higher_user_id)
   REFERENCES direct_conversations(id,lower_user_id,higher_user_id) ON DELETE RESTRICT,
 CONSTRAINT ck_direct_message_sender CHECK(sender_id IN(lower_user_id,higher_user_id)),
 CONSTRAINT ck_direct_message_number CHECK(message_number>0),
 CONSTRAINT ck_direct_message_body CHECK(length(btrim(body,E' \t\n\r'))>0),
 CONSTRAINT uq_direct_message_number UNIQUE(conversation_id,message_number),
 CONSTRAINT uq_direct_message_retry UNIQUE(conversation_id,sender_id,client_message_id)
);
CREATE INDEX ix_direct_message_sender ON direct_messages(sender_id);
CREATE INDEX ix_direct_message_unread ON direct_messages(conversation_id,message_number,sender_id);

CREATE TABLE direct_conversation_states (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL,
 lower_user_id BIGINT NOT NULL,
 higher_user_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 last_read_message_number BIGINT NOT NULL DEFAULT 0,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT fk_direct_state_pair FOREIGN KEY(conversation_id,lower_user_id,higher_user_id)
   REFERENCES direct_conversations(id,lower_user_id,higher_user_id) ON DELETE RESTRICT,
 CONSTRAINT ck_direct_state_participant CHECK(user_id IN(lower_user_id,higher_user_id)),
 CONSTRAINT ck_direct_state_read CHECK(last_read_message_number>=0),
 CONSTRAINT ck_direct_state_version CHECK(version>=0),
 CONSTRAINT uq_direct_state_user UNIQUE(conversation_id,user_id)
);
CREATE INDEX ix_direct_state_user ON direct_conversation_states(user_id,conversation_id);

CREATE TABLE user_blocks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_user_block_pair CHECK(blocker_id<>blocked_id),
 CONSTRAINT uq_user_block_pair UNIQUE(blocker_id,blocked_id),
 CONSTRAINT ck_user_block_version CHECK(version>=0),
 CONSTRAINT ck_user_block_time CHECK(updated_at>=created_at)
);
CREATE INDEX ix_user_block_active ON user_blocks(blocker_id,blocked_id) WHERE active=true;
CREATE INDEX ix_user_block_target ON user_blocks(blocked_id);
