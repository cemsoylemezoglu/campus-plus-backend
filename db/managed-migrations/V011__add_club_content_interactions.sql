CREATE TABLE club_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT REFERENCES events(id) ON DELETE RESTRICT,
 announcement_id BIGINT REFERENCES club_announcements(id) ON DELETE RESTRICT,
 author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 root_id BIGINT,
 body VARCHAR(3000) NOT NULL,
 status VARCHAR(16) NOT NULL,
 resource_hidden BOOLEAN NOT NULL DEFAULT false,
 platform_hidden BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 removed_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_club_comments_source CHECK((event_id IS NOT NULL)::int+(announcement_id IS NOT NULL)::int=1),
 CONSTRAINT uq_club_comments_id_event UNIQUE(id,event_id),
 CONSTRAINT uq_club_comments_id_announcement UNIQUE(id,announcement_id),
 CONSTRAINT fk_club_comments_root FOREIGN KEY(root_id) REFERENCES club_comments(id) ON DELETE RESTRICT,
 CONSTRAINT fk_club_comments_root_event FOREIGN KEY(root_id,event_id) REFERENCES club_comments(id,event_id) ON DELETE RESTRICT,
 CONSTRAINT fk_club_comments_root_announcement FOREIGN KEY(root_id,announcement_id) REFERENCES club_comments(id,announcement_id) ON DELETE RESTRICT,
 CONSTRAINT ck_club_comments_root CHECK(root_id IS NULL OR root_id<>id),
 CONSTRAINT ck_club_comments_status CHECK(status IN ('ACTIVE','REMOVED')),
 CONSTRAINT ck_club_comments_body CHECK(length(btrim(body,E' \t\n\r'))>0),
 CONSTRAINT ck_club_comments_version CHECK(version>=0),
 CONSTRAINT ck_club_comments_lifecycle CHECK((status='ACTIVE' AND removed_at IS NULL) OR (status='REMOVED' AND removed_at IS NOT NULL)),
 CONSTRAINT ck_club_comments_times CHECK(updated_at>=created_at AND (removed_at IS NULL OR (removed_at>=created_at AND updated_at>=removed_at)))
);
CREATE INDEX ix_club_comments_event_roots ON club_comments(event_id,created_at,id) WHERE root_id IS NULL AND event_id IS NOT NULL;
CREATE INDEX ix_club_comments_announcement_roots ON club_comments(announcement_id,created_at,id) WHERE root_id IS NULL AND announcement_id IS NOT NULL;
CREATE INDEX ix_club_comments_replies ON club_comments(root_id,created_at,id) WHERE root_id IS NOT NULL;
CREATE INDEX ix_club_comments_author_id ON club_comments(author_id,id DESC);
CREATE INDEX ix_club_comments_event ON club_comments(event_id) WHERE event_id IS NOT NULL;
CREATE INDEX ix_club_comments_announcement ON club_comments(announcement_id) WHERE announcement_id IS NOT NULL;
CREATE TABLE club_content_likes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT REFERENCES events(id) ON DELETE RESTRICT,
 announcement_id BIGINT REFERENCES club_announcements(id) ON DELETE RESTRICT,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_club_content_likes_source CHECK((event_id IS NOT NULL)::int+(announcement_id IS NOT NULL)::int=1),
 CONSTRAINT uq_club_content_likes_event_user UNIQUE(event_id,user_id),
 CONSTRAINT uq_club_content_likes_announcement_user UNIQUE(announcement_id,user_id),
 CONSTRAINT ck_club_content_likes_version CHECK(version>=0),
 CONSTRAINT ck_club_content_likes_times CHECK(updated_at>=created_at)
);
CREATE INDEX ix_club_content_likes_event_active ON club_content_likes(event_id) WHERE active=true AND event_id IS NOT NULL;
CREATE INDEX ix_club_content_likes_announcement_active ON club_content_likes(announcement_id) WHERE active=true AND announcement_id IS NOT NULL;
CREATE INDEX ix_club_content_likes_user ON club_content_likes(user_id);
CREATE TABLE club_comment_likes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL REFERENCES club_comments(id) ON DELETE RESTRICT,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uq_club_comment_likes_user UNIQUE(comment_id,user_id),
 CONSTRAINT ck_club_comment_likes_version CHECK(version>=0),
 CONSTRAINT ck_club_comment_likes_times CHECK(updated_at>=created_at)
);
CREATE INDEX ix_club_comment_likes_active ON club_comment_likes(comment_id) WHERE active=true;
CREATE INDEX ix_club_comment_likes_user ON club_comment_likes(user_id);
CREATE TABLE club_comment_moderation_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL REFERENCES club_comments(id) ON DELETE RESTRICT,
 actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 scope VARCHAR(16) NOT NULL,
 action VARCHAR(16) NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 resulting_version BIGINT NOT NULL,
 CONSTRAINT uq_club_comment_moderation_version UNIQUE(comment_id,resulting_version),
 CONSTRAINT ck_club_comment_moderation_scope CHECK(scope IN ('RESOURCE','PLATFORM')),
 CONSTRAINT ck_club_comment_moderation_action CHECK(action IN ('HIDE','RESTORE')),
 CONSTRAINT ck_club_comment_moderation_reason CHECK(length(btrim(reason,E' \t\n\r'))>0),
 CONSTRAINT ck_club_comment_moderation_version CHECK(resulting_version>=0)
);
CREATE INDEX ix_club_comment_moderation_history ON club_comment_moderation_actions(comment_id,id DESC);
CREATE INDEX ix_club_comment_moderation_actor ON club_comment_moderation_actions(actor_id);
