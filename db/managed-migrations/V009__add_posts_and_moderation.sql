-- Flyway owns the transaction. No seed, backfill, record deletion or runtime grants.
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';
SET LOCAL search_path=public,pg_catalog;
DO $$ BEGIN
    IF current_database() NOT IN ('campus_plus','campus_plus_test')
       OR host(inet_server_addr()) IS DISTINCT FROM '127.0.0.1'
       OR inet_server_port() IS DISTINCT FROM 5434
       OR current_setting('server_version_num')::int NOT BETWEEN 170000 AND 179999 THEN
        RAISE EXCEPTION 'Unauthorized Campus+ PostgreSQL 17 migration target';
    END IF;
    IF NOT EXISTS(SELECT FROM public.flyway_schema_history WHERE version IN ('8','008') AND type='SQL' AND success) THEN
        RAISE EXCEPTION 'Successful reviewed V008 migration required';
    END IF;
END $$;

-- Existing rows/columns are preserved. PK id already makes every pair unique.
-- Building this supporting index briefly locks clubs; bounded by the timeouts above.
ALTER TABLE clubs ADD CONSTRAINT uq_clubs_id_university UNIQUE(id,university_id);

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id BIGINT NOT NULL REFERENCES universities(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    publisher VARCHAR(16) NOT NULL,
    club_id BIGINT REFERENCES clubs(id) ON DELETE RESTRICT,
    body VARCHAR(10000) NOT NULL,
    audience VARCHAR(24) NOT NULL,
    status VARCHAR(16) NOT NULL,
    published_at TIMESTAMPTZ,
    removed_at TIMESTAMPTZ,
    removed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    removal_reason VARCHAR(1000),
    moderation_hidden BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_posts_club_university FOREIGN KEY(club_id,university_id)
        REFERENCES clubs(id,university_id) ON DELETE RESTRICT,
    CONSTRAINT ck_posts_publisher CHECK(publisher IN ('STUDENT','CLUB')),
    CONSTRAINT ck_posts_audience CHECK(audience IN ('UNIVERSITY_STUDENTS','CLUB_MEMBERS')),
    CONSTRAINT ck_posts_status CHECK(status IN ('DRAFT','PUBLISHED','REMOVED')),
    CONSTRAINT ck_posts_source CHECK(
        (publisher='STUDENT' AND club_id IS NULL AND audience='UNIVERSITY_STUDENTS') OR
        (publisher='CLUB' AND club_id IS NOT NULL)),
    CONSTRAINT ck_posts_body CHECK(length(btrim(body, E' \t\n\r'))>0),
    CONSTRAINT ck_posts_version CHECK(version>=0),
    CONSTRAINT ck_posts_lifecycle CHECK(
        (status='DRAFT' AND published_at IS NULL AND removed_at IS NULL AND removed_by IS NULL AND removal_reason IS NULL) OR
        (status='PUBLISHED' AND published_at IS NOT NULL AND removed_at IS NULL AND removed_by IS NULL AND removal_reason IS NULL) OR
        (status='REMOVED' AND removed_at IS NOT NULL AND removed_by IS NOT NULL AND removal_reason IS NOT NULL
            AND length(btrim(removal_reason, E' \t\n\r'))>0)),
    CONSTRAINT ck_posts_times CHECK(updated_at>=created_at AND (published_at IS NULL OR published_at>=created_at)
        AND (removed_at IS NULL OR removed_at>=created_at) AND (published_at IS NULL OR updated_at>=published_at)
        AND (removed_at IS NULL OR updated_at>=removed_at) AND (removed_at IS NULL OR published_at IS NULL OR removed_at>=published_at))
);
CREATE INDEX ix_posts_feed ON posts(university_id,published_at DESC,id DESC)
    WHERE status='PUBLISHED' AND moderation_hidden=false;
CREATE INDEX ix_posts_club_feed ON posts(club_id,published_at DESC,id DESC)
    WHERE status='PUBLISHED' AND moderation_hidden=false;
CREATE INDEX ix_posts_creator_id ON posts(created_by,id DESC);
CREATE INDEX ix_posts_club_id ON posts(club_id,id) WHERE club_id IS NOT NULL;
CREATE INDEX ix_posts_removed_by ON posts(removed_by) WHERE removed_by IS NOT NULL;
-- university_id support also provided by ix_posts_feed only for published rows;
-- a full FK index is necessary for other lifecycle states.
CREATE INDEX ix_posts_university ON posts(university_id);

CREATE TABLE post_moderation_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE RESTRICT,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    action VARCHAR(16) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    resulting_version BIGINT NOT NULL,
    CONSTRAINT uq_post_moderation_version UNIQUE(post_id,resulting_version),
    CONSTRAINT ck_post_moderation_action CHECK(action IN ('HIDE','RESTORE')),
    CONSTRAINT ck_post_moderation_reason CHECK(length(btrim(reason, E' \t\n\r'))>0),
    CONSTRAINT ck_post_moderation_version CHECK(resulting_version>=0)
);
CREATE INDEX ix_post_moderation_post_id ON post_moderation_actions(post_id,id DESC);
CREATE INDEX ix_post_moderation_actor ON post_moderation_actions(actor_id);
