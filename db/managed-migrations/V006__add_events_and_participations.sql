CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    venue VARCHAR(500) NOT NULL,
    cover_url VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    audience VARCHAR(24) NOT NULL DEFAULT 'UNIVERSITY_STUDENTS',
    capacity INTEGER,
    registration_opens_at TIMESTAMPTZ NOT NULL,
    registration_closes_at TIMESTAMPTZ NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    time_zone VARCHAR(64) NOT NULL,
    published_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    cancellation_reason VARCHAR(1000),
    completed_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,
    schedule_changed_at TIMESTAMPTZ,
    schedule_change_reason VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_events_title CHECK (length(btrim(title))>0),
    CONSTRAINT ck_events_description CHECK (length(btrim(description))>0),
    CONSTRAINT ck_events_venue CHECK (length(btrim(venue))>0),
    CONSTRAINT ck_events_time_zone CHECK (length(btrim(time_zone))>0),
    CONSTRAINT ck_events_status CHECK (status IN ('DRAFT','PUBLISHED','CANCELLED','COMPLETED')),
    CONSTRAINT ck_events_audience CHECK (audience IN ('UNIVERSITY_STUDENTS','CLUB_MEMBERS')),
    CONSTRAINT ck_events_capacity CHECK (capacity IS NULL OR capacity>0),
    CONSTRAINT ck_events_schedule CHECK (registration_opens_at<registration_closes_at
        AND registration_closes_at<=starts_at AND starts_at<ends_at),
    CONSTRAINT ck_events_version CHECK (version>=0),
    CONSTRAINT ck_events_published CHECK ((status NOT IN ('PUBLISHED','COMPLETED') OR published_at IS NOT NULL)
        AND (status<>'DRAFT' OR published_at IS NULL)),
    CONSTRAINT ck_events_cancelled CHECK ((status='CANCELLED' AND cancelled_at IS NOT NULL
        AND cancelled_by IS NOT NULL AND cancellation_reason IS NOT NULL AND length(btrim(cancellation_reason))>0)
        OR (status<>'CANCELLED' AND cancelled_at IS NULL AND cancelled_by IS NULL AND cancellation_reason IS NULL)),
    CONSTRAINT ck_events_completed CHECK ((status='COMPLETED' AND completed_at IS NOT NULL)
        OR (status<>'COMPLETED' AND completed_at IS NULL)),
    CONSTRAINT ck_events_archived CHECK (archived_at IS NULL OR status IN ('CANCELLED','COMPLETED')),
    CONSTRAINT ck_events_reschedule_reason CHECK (schedule_change_reason IS NULL OR schedule_changed_at IS NOT NULL)
);
CREATE INDEX ix_events_club_status_start_id ON events(club_id,status,starts_at,id);
CREATE INDEX ix_events_discovery ON events(status,starts_at,id) WHERE archived_at IS NULL;
CREATE INDEX ix_events_created_by ON events(created_by);
CREATE INDEX ix_events_cancelled_by ON events(cancelled_by) WHERE cancelled_by IS NOT NULL;

CREATE TABLE event_participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES student_profiles(user_id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'REGISTERED',
    registered_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    ended_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    end_cause VARCHAR(32),
    decision_reason VARCHAR(1000),
    checked_in_at TIMESTAMPTZ,
    checked_in_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_event_participations_event_user UNIQUE(event_id,user_id),
    CONSTRAINT ck_event_participations_status CHECK (status IN ('REGISTERED','CANCELLED','REMOVED','ATTENDED','NO_SHOW')),
    CONSTRAINT ck_event_participations_cause CHECK (end_cause IN ('SELF_CANCELLED','EVENT_CANCELLED',
        'MEMBERSHIP_ENDED','CLUB_ARCHIVED','REMOVED','REAPPLICATION_ALLOWED','NO_SHOW')),
    CONSTRAINT ck_event_participations_version CHECK (version>=0),
    CONSTRAINT ck_event_participations_state CHECK (
        (status='REGISTERED' AND ended_at IS NULL AND ended_by IS NULL AND end_cause IS NULL
            AND decision_reason IS NULL AND checked_in_at IS NULL AND checked_in_by IS NULL)
        OR (status='ATTENDED' AND ended_at IS NULL AND ended_by IS NULL AND end_cause IS NULL
            AND decision_reason IS NULL AND checked_in_at IS NOT NULL AND checked_in_by IS NOT NULL)
        OR (status IN ('CANCELLED','REMOVED','NO_SHOW') AND ended_at IS NOT NULL AND ended_by IS NOT NULL
            AND end_cause IS NOT NULL AND checked_in_at IS NULL AND checked_in_by IS NULL)),
    CONSTRAINT ck_event_participations_end_cause CHECK (
        (status='CANCELLED' AND end_cause IN ('SELF_CANCELLED','EVENT_CANCELLED','MEMBERSHIP_ENDED','CLUB_ARCHIVED','REAPPLICATION_ALLOWED'))
        OR (status='REMOVED' AND end_cause='REMOVED' AND decision_reason IS NOT NULL AND length(btrim(decision_reason))>0)
        OR (status='NO_SHOW' AND end_cause='NO_SHOW') OR status IN ('REGISTERED','ATTENDED'))
);
CREATE INDEX ix_event_participations_event_status_id ON event_participations(event_id,status,id);
CREATE INDEX ix_event_participations_user_status_event ON event_participations(user_id,status,event_id);
CREATE INDEX ix_event_participations_user_id ON event_participations(user_id,id);
CREATE INDEX ix_event_participations_ended_by ON event_participations(ended_by) WHERE ended_by IS NOT NULL;
CREATE INDEX ix_event_participations_checked_in_by ON event_participations(checked_in_by) WHERE checked_in_by IS NOT NULL;

