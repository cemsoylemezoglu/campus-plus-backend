CREATE TABLE public."universities" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "code" character varying(30) NOT NULL,
    "name" character varying(200) NOT NULL,
    "city" character varying(100) NOT NULL,
    "country_code" character varying(2) NOT NULL,
    "website_url" character varying(500),
    "active" boolean DEFAULT true NOT NULL,
    "created_at" timestamp with time zone NOT NULL,
    "updated_at" timestamp with time zone NOT NULL,
    "version" bigint DEFAULT 0 NOT NULL,
    CONSTRAINT "ck_universities_city" CHECK ((length(btrim((city)::text)) > 0)),
    CONSTRAINT "ck_universities_code" CHECK (((code)::text ~ '^[A-Z0-9][A-Z0-9_-]*$'::text)),
    CONSTRAINT "ck_universities_country" CHECK (((country_code)::text ~ '^[A-Z]{2}$'::text)),
    CONSTRAINT "ck_universities_name" CHECK ((length(btrim((name)::text)) > 0)),
    CONSTRAINT "ck_universities_version" CHECK ((version >= 0)),
    CONSTRAINT "universities_pkey" PRIMARY KEY (id),
    CONSTRAINT "uq_universities_code" UNIQUE (code)
);

CREATE INDEX ix_universities_active_id ON public.universities USING btree (active, id);

CREATE TABLE public."student_profiles" (
    "user_id" bigint NOT NULL,
    "university_id" bigint NOT NULL,
    "department" character varying(150) NOT NULL,
    "study_year" smallint,
    "bio" character varying(1000),
    "created_at" timestamp with time zone NOT NULL,
    "updated_at" timestamp with time zone NOT NULL,
    "version" bigint DEFAULT 0 NOT NULL,
    CONSTRAINT "ck_student_profiles_department" CHECK ((length(btrim((department)::text)) > 0)),
    CONSTRAINT "ck_student_profiles_version" CHECK ((version >= 0)),
    CONSTRAINT "ck_student_profiles_year" CHECK (((study_year >= 0) AND (study_year <= 8))),
