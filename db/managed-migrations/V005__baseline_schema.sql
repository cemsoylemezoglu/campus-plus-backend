    "updated_at" timestamp with time zone NOT NULL,
    "version" bigint DEFAULT 0 NOT NULL,
    CONSTRAINT "ck_clubs_description" CHECK ((length(btrim((description)::text)) > 0)),
    CONSTRAINT "ck_clubs_name" CHECK ((length(btrim((name)::text)) > 0)),
    CONSTRAINT "ck_clubs_slug" CHECK (((slug)::text ~ '^[a-z0-9]+(-[a-z0-9]+)*$'::text)),
    CONSTRAINT "ck_clubs_status" CHECK (((status)::text = ANY ((ARRAY['PENDING_APPROVAL'::character varying, 'ACTIVE'::character varying, 'REJECTED'::character varying, 'SUSPENDED'::character varying, 'ARCHIVED'::character varying])::text[]))),
    CONSTRAINT "ck_clubs_version" CHECK ((version >= 0)),
