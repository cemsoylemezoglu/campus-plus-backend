    "logo_url" character varying(500),
    "status" character varying(24) DEFAULT 'PENDING_APPROVAL'::character varying NOT NULL,
    "review_note" character varying(1000),
    "reviewed_by" bigint,
    "reviewed_at" timestamp with time zone,
