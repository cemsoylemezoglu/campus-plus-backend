    CONSTRAINT "clubs_pkey" PRIMARY KEY (id),
    CONSTRAINT "clubs_reviewed_by_fkey" FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT "clubs_university_id_fkey" FOREIGN KEY (university_id) REFERENCES universities(id) ON DELETE RESTRICT,
    CONSTRAINT "uq_clubs_university_slug" UNIQUE (university_id, slug)
);

CREATE INDEX ix_clubs_status_id ON public.clubs USING btree (status, id);
