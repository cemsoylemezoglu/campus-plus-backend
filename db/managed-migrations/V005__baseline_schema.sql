CREATE TABLE public."club_memberships" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "club_id" bigint NOT NULL,
    "user_id" bigint NOT NULL,
    "role" character varying(16) DEFAULT 'MEMBER'::character varying NOT NULL,
    "status" character varying(16) DEFAULT 'PENDING'::character varying NOT NULL,
    "requested_at" timestamp with time zone NOT NULL,
    "joined_at" timestamp with time zone,
    "ended_at" timestamp with time zone,
    "reviewed_by" bigint,
    "reviewed_at" timestamp with time zone,
    "decision_reason" character varying(1000),
    "created_at" timestamp with time zone NOT NULL,
    "updated_at" timestamp with time zone NOT NULL,
    "version" bigint DEFAULT 0 NOT NULL,
    CONSTRAINT "ck_club_memberships_active_joined" CHECK ((((status)::text <> 'ACTIVE'::text) OR (joined_at IS NOT NULL))),
    CONSTRAINT "ck_club_memberships_active_role" CHECK ((((status)::text = 'ACTIVE'::text) OR ((role)::text = 'MEMBER'::text))),
    CONSTRAINT "ck_club_memberships_role" CHECK (((role)::text = ANY ((ARRAY['MEMBER'::character varying, 'MANAGER'::character varying, 'OWNER'::character varying])::text[]))),
    CONSTRAINT "ck_club_memberships_status" CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'ACTIVE'::character varying, 'REJECTED'::character varying, 'LEFT'::character varying, 'REMOVED'::character varying, 'SUSPENDED'::character varying])::text[]))),
    CONSTRAINT "ck_club_memberships_version" CHECK ((version >= 0)),
    CONSTRAINT "club_memberships_club_id_fkey" FOREIGN KEY (club_id) REFERENCES clubs(id) ON DELETE RESTRICT,
    CONSTRAINT "club_memberships_pkey" PRIMARY KEY (id),
    CONSTRAINT "club_memberships_reviewed_by_fkey" FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT "club_memberships_user_id_fkey" FOREIGN KEY (user_id) REFERENCES student_profiles(user_id) ON DELETE RESTRICT,
    CONSTRAINT "uq_club_memberships_club_user" UNIQUE (club_id, user_id)
);

CREATE INDEX ix_club_memberships_club_status_role_id ON public.club_memberships USING btree (club_id, status, role, id);
CREATE INDEX ix_club_memberships_user_status_id ON public.club_memberships USING btree (user_id, status, id);
CREATE UNIQUE INDEX uq_club_single_active_owner ON public.club_memberships USING btree (club_id) WHERE (((role)::text = 'OWNER'::text) AND ((status)::text = 'ACTIVE'::text));
