-- PROPOSAL ONLY: requires explicit user approval. Not applied or auto-run.
-- V004 and V005 must BOTH be applied before starting the new application.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';
DO $$
DECLARE
    snapshot_users jsonb;
    snapshot_user_roles jsonb;
    snapshot_universities jsonb;
    snapshot_student_profiles jsonb;
BEGIN
    IF current_database() <> 'campus_plus'
        OR inet_server_addr() IS DISTINCT FROM '127.0.0.1'::inet
        OR inet_server_port() IS DISTINCT FROM 5434
        OR current_setting('server_version_num')::integer NOT BETWEEN 170000 AND 179999 THEN
        RAISE EXCEPTION 'Not the authorized Campus+ PostgreSQL 17 target';
    END IF;
    IF to_regclass('public.clubs') IS NOT NULL THEN
        RAISE EXCEPTION 'Unexpected existing clubs table; inspect before proceeding';
    END IF;

    LOCK TABLE public.users, public.user_roles, public.universities, public.student_profiles IN SHARE MODE;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) INTO snapshot_users FROM public.users t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id, role), '[]'::jsonb) INTO snapshot_user_roles FROM public.user_roles t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) INTO snapshot_universities FROM public.universities t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id), '[]'::jsonb) INTO snapshot_student_profiles FROM public.student_profiles t;
    CREATE TABLE public.clubs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        university_id BIGINT NOT NULL REFERENCES public.universities(id) ON DELETE RESTRICT,
        created_by BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
        name VARCHAR(150) NOT NULL,
        slug VARCHAR(100) NOT NULL,
        description VARCHAR(5000) NOT NULL,
        logo_url VARCHAR(500),
        status VARCHAR(24) NOT NULL DEFAULT 'PENDING_APPROVAL',
        review_note VARCHAR(1000),
        reviewed_by BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
        reviewed_at TIMESTAMPTZ,
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL,
        version BIGINT NOT NULL DEFAULT 0,
        CONSTRAINT uq_clubs_university_slug UNIQUE(university_id, slug),
        CONSTRAINT ck_clubs_name CHECK(length(btrim(name))>0),
        CONSTRAINT ck_clubs_description CHECK(length(btrim(description))>0),
        CONSTRAINT ck_clubs_slug CHECK(slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
        CONSTRAINT ck_clubs_status CHECK(status IN ('PENDING_APPROVAL','ACTIVE','REJECTED','SUSPENDED','ARCHIVED')),
        CONSTRAINT ck_clubs_version CHECK(version>=0)
    );
    CREATE INDEX ix_clubs_university_status_id ON public.clubs(university_id,status,id);
    CREATE INDEX ix_clubs_status_id ON public.clubs(status,id);
    IF
        snapshot_users IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) FROM public.users t) OR
        snapshot_user_roles IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id, role), '[]'::jsonb) FROM public.user_roles t) OR
        snapshot_universities IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) FROM public.universities t) OR
        snapshot_student_profiles IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id), '[]'::jsonb) FROM public.student_profiles t) THEN
        RAISE EXCEPTION 'Existing account, role or academic data were not preserved';
    END IF;
END $$;
COMMIT;
