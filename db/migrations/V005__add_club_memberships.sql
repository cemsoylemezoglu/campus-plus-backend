-- PROPOSAL ONLY: requires explicit user approval. Not applied or auto-run.
-- V004 and V005 must BOTH be applied before starting the new application.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';
DO $$
DECLARE
    snapshot_users jsonb;
    snapshot_user_roles jsonb;
    snapshot_universities jsonb;
    snapshot_student_profiles jsonb;
    snapshot_clubs jsonb;
BEGIN
    IF current_database() <> 'campus_plus'
        OR inet_server_addr() IS DISTINCT FROM '127.0.0.1'::inet
        OR inet_server_port() IS DISTINCT FROM 5434
        OR current_setting('server_version_num')::integer NOT BETWEEN 170000 AND 179999 THEN
        RAISE EXCEPTION 'Not the authorized Campus+ PostgreSQL 17 target';
    END IF;
    IF to_regclass('public.club_memberships') IS NOT NULL THEN
        RAISE EXCEPTION 'Unexpected existing club_memberships table; inspect before proceeding';
    END IF;
    IF to_regclass('public.clubs') IS NULL THEN
        RAISE EXCEPTION 'Apply the approved V004 first';
    END IF;
    LOCK TABLE public.users, public.user_roles, public.universities, public.student_profiles, public.clubs IN SHARE MODE;
    IF EXISTS (SELECT 1 FROM public.clubs) THEN
        RAISE EXCEPTION 'Unexpected existing clubs without memberships; inspect before proceeding';
    END IF;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) INTO snapshot_users FROM public.users t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id, role), '[]'::jsonb) INTO snapshot_user_roles FROM public.user_roles t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) INTO snapshot_universities FROM public.universities t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id), '[]'::jsonb) INTO snapshot_student_profiles FROM public.student_profiles t;
    SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) INTO snapshot_clubs FROM public.clubs t;
    CREATE TABLE public.club_memberships (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        club_id BIGINT NOT NULL REFERENCES public.clubs(id) ON DELETE RESTRICT,
        user_id BIGINT NOT NULL REFERENCES public.student_profiles(user_id) ON DELETE RESTRICT,
        role VARCHAR(16) NOT NULL DEFAULT 'MEMBER',
        status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
        requested_at TIMESTAMPTZ NOT NULL,
        joined_at TIMESTAMPTZ,
        ended_at TIMESTAMPTZ,
        reviewed_by BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
        reviewed_at TIMESTAMPTZ,
        decision_reason VARCHAR(1000),
        created_at TIMESTAMPTZ NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL,
        version BIGINT NOT NULL DEFAULT 0,
        CONSTRAINT uq_club_memberships_club_user UNIQUE(club_id,user_id),
        CONSTRAINT ck_club_memberships_role CHECK(role IN ('MEMBER','MANAGER','OWNER')),
        CONSTRAINT ck_club_memberships_status CHECK(status IN ('PENDING','ACTIVE','REJECTED','LEFT','REMOVED','SUSPENDED')),
        CONSTRAINT ck_club_memberships_active_role CHECK(status='ACTIVE' OR role='MEMBER'),
        CONSTRAINT ck_club_memberships_active_joined CHECK(status<>'ACTIVE' OR joined_at IS NOT NULL),
        CONSTRAINT ck_club_memberships_version CHECK(version>=0)
    );
    CREATE UNIQUE INDEX uq_club_single_active_owner ON public.club_memberships(club_id)
        WHERE role='OWNER' AND status='ACTIVE';
    CREATE INDEX ix_club_memberships_user_status_id ON public.club_memberships(user_id,status,id);
    CREATE INDEX ix_club_memberships_club_status_role_id ON public.club_memberships(club_id,status,role,id);
    IF
        snapshot_users IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) FROM public.users t) OR
        snapshot_user_roles IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id, role), '[]'::jsonb) FROM public.user_roles t) OR
        snapshot_universities IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) FROM public.universities t) OR
        snapshot_student_profiles IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY user_id), '[]'::jsonb) FROM public.student_profiles t) OR
        snapshot_clubs IS DISTINCT FROM (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) FROM public.clubs t) THEN
        RAISE EXCEPTION 'Existing account, role or academic data were not preserved';
    END IF;
END $$;
COMMIT;
